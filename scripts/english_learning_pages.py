"""Render the English learning routes from reviewed source units."""

from __future__ import annotations

from hashlib import sha256
from html import escape
from pathlib import Path
from posixpath import relpath
from urllib.parse import quote

if __package__:
    from . import english_learning_sources as source
    from . import generate_learning_cards as zh
else:
    import english_learning_sources as source
    import generate_learning_cards as zh


PREFIX = "learning/"
NOTICE = "<!-- Generated by scripts/english_learning_pages.py; edit the reviewed English sources. -->"
HIDE_TOC = ["---", "hide:", "  - toc", "---", ""]


def _md(target: str, path: str) -> str:
    return relpath(target, str(Path(path).parent))


def _html(target: str, path: str) -> str:
    return zh._page_href(target, f"en/{path}")


def _title(text: str) -> str:
    return escape(" ".join(text.split()), quote=False).translate(
        str.maketrans({"[": "&#91;", "]": "&#93;", "|": "&#124;"})
    )


def _source_ref(label: str) -> str:
    # These are provenance labels for the Chinese original, not duplicate
    # translations of article headings. Preserve their text to aid lookup.
    return label


def _page(root: Path, path: str, title: str, body: list[str], *, toc: bool = False) -> str:
    original = f"docs/{path}"
    digest = sha256((root / original).read_bytes()).hexdigest()
    other = _md(path, f"en/{path}")
    return "\n".join([
        *([] if toc else HIDE_TOC), NOTICE, f"<!-- source-sha256: {digest} -->", "",
        f"# {title}", "", f"[简体中文]({other}) · English", "", *body,
    ]).rstrip() + "\n"


def _deep_dive(root, path, topic, dive, by_identity):
    def papers(ids):
        return " · ".join(
            f"[{_title(by_identity[i]['title'])}]({_md('../' + by_identity[i]['detail_path'], path)})"
            for i in ids
        )

    body = [
        f"Updated {dive['updated']} · {len(topic['papers'])} topic entries / "
        f"{len(dive['comparisons'])} representative comparisons", "",
        dive["thesis"], "",
        "[Mechanisms](#comparison) · [Trade-offs](#analysis) · "
        "[Cross-paper questions](#questions) · [Updates](#updates)", "",
        '!!! note "How to read this card"', "",
        "    The table compares representative methods. It is not a shared-benchmark leaderboard. "
        "Teaching examples are not measured results.", "",
        "## Mechanism comparison {#comparison}", "", "Axes: " + " · ".join(dive["axes"]), "",
        '<div class="ar-deep-comparison" markdown="1">', "",
        "| Paper and source | Mechanism | Benefits and trade-offs |", "| --- | --- | --- |",
    ]
    for row in dive["comparisons"]:
        url = quote(by_identity[row["paper"]]["paper_url"], safe=":/?&=%#@+,;~.-_")
        refs = ", ".join(_title(_source_ref(section)) for section in row["sections"])
        body.append(
            f"| {papers([row['paper']])} · [Original source]({url})"
            f"<br>Sections in the Chinese source: {refs} "
            f"| {_title(row['position'])} | {_title(row['tradeoff'])} |"
        )
    body += ["", "</div>", "", "## Trade-off analysis {#analysis}", ""]
    for row in dive["analysis"]:
        body += [f"### {row['title']}", "", row["body"], "", f"Sources: {papers(row['papers'])}", ""]
    body += ["## Cross-paper questions {#questions}", "",
             "Try answering before expanding the explanation. Each question relates at least two papers.", ""]
    for row in dive["questions"]:
        body += [f"### {row['question']} {{#cross-{row['id']}}}", "", '??? note "Show answer and example"', ""]
        details = [f"**Answer:** {row['answer']}", "", f"**Illustrative example:** {row['example']}",
                   "", f"Sources: {papers(row['papers'])}"]
        body += ["    " + line if line else "" for value in details for line in value.split("\n")]
        body.append("")
    body += ["## Update log {#updates}", "",
             "Updates record new approaches, changed trade-offs, and follow-up evidence.", ""]
    for update in reversed(dive["updates"]):
        refs = (f"Affected: {papers(update['papers'])}" if len(update["papers"]) <= 8
                else f"Covers {len(update['papers'])} topic entries; see the full list below.")
        body += [f"**{update['date']}** · {update['summary']}", "", refs, ""]
    body += [
        f'<details class="ar-deep-catalog" markdown="1"><summary>All {len(topic["papers"])} topic entries</summary>',
        "", "The full catalog follows. The main comparison covers the representative papers listed above.", "",
        *[f"- {papers([identity])}" for identity in topic["papers"]], "", "</details>", "",
        f"[Paper-by-paper questions]({_md(topic['path'], path)}) · [All deep dives]({_md(PREFIX + 'deep-dives/index.md', path)})",
    ]
    return _page(root, path, dive["title"], body)


def render_pages(root: Path) -> dict[str, str]:
    """Build all 73 routes atomically in memory; never publish a partial bank."""
    cards, themes = zh._collection(root)
    bank = {card["identity"]: card["questions"] for card in cards}
    deep = zh._deep_dive_module()
    qa = zh._question_module()
    dives = deep.load_deep_dives(root, themes, cards, qa.source_headings, required=True)
    units = source.question_units(bank) | source.topic_units(themes) | source.deep_dive_units(dives)
    reviewed = source.load_reviewed(root / "docs/en/learning/translations", units)
    bank = source.localize_questions(bank, reviewed)
    themes = source.localize_topics(themes, reviewed)
    dives = source.localize_deep_dives(dives, reviewed)
    zh._topic_module().assign_topics(cards, themes)
    for card in cards:
        original = Path(card["detail_path"])
        sibling = original.with_name("README-en.md").as_posix()
        if not (root / "docs" / sibling).is_file():
            raise ValueError(f"English learning links require the reviewed write-up: {sibling}")
        card.update(questions=bank[card["identity"]], detail_path=sibling, topic_path="en/" + card["topic_path"])
        card["source_label"] = "Original source" if card["source_label"] == "原始资料" else "Original paper"
        if card["theme"] == "inbox":
            card["theme_title"] = "Unclassified"
        if card["curated_path"]:
            card["curated_path"] = "en/" + card["curated_path"]
        if card["organization"] == "未标注机构":
            card["organization"] = "Institution not recorded"
        if card["published"] == "未标注":
            card["published"] = "Not recorded"
    by_identity = {card["identity"]: card for card in cards}
    output = {}

    def add(path, title, body):
        output[f"docs/en/{path}"] = _page(root, path, title, body)

    def browser(rows, path, *, filters=True):
        return zh.render_browser(rows, themes, path="en/" + path, filters=filters, english=True)

    recent = zh._recent_cards(cards)
    add(PREFIX + "all.md", "All paper questions", [
        "Study each paper in four levels: basics, core mechanism, method comparison, and implementation. "
        "Try the question before expanding the answer and teaching example.", "",
        "[Browse themes](index.md) · [Recent questions](recent.md)", "", browser(cards, PREFIX + "all.md"),
    ])
    add(PREFIX + "recent.md", "Recently added questions", [
        "Ordered by the date each question was added, including new questions about older papers. "
        "Questions also appear in their topic banks.", "", browser(recent, PREFIX + "recent.md"),
    ])
    inbox = [card for card in cards if card["theme"] == "inbox"]
    add(PREFIX + "inbox.md", "Unclassified papers", [
        "New papers receive their questions before final topic assignment. "
        "This inbox keeps unassigned entries discoverable.", "",
        f"{len(inbox)} papers remain unclassified." if inbox else "All papers are currently classified.", "",
        browser(inbox, PREFIX + "inbox.md", filters=False) if inbox else "",
        "[Learning themes](index.md) · [Search all questions](all.md)",
    ])
    index_path = PREFIX + "index.md"
    index = [
        "Work from **basic understanding → core mechanism → method comparison → implementation details**. "
        "Try answering first, then reveal explanations and teaching examples. You can filter by level.", "",
        '<div class="ar-learning-actions" markdown="1">', "",
        "[Topic deep dives](deep-dives/index.md){ .md-button .md-button--primary }",
        "[Search all questions](all.md){ .md-button }",
        "[Recently added](recent.md){ .md-button }", "", "</div>", "",
        "## Study by theme", "",
        "Use a subtopic bank for paper-by-paper study, or a deep dive for comparisons, trade-offs, and cross-paper Q&A.", "",
        f"{len(themes)} themes · {sum(len(t['topics']) for t in themes)} subtopics · "
        f"{qa.question_count(cards)} questions across {len(cards)} papers", "",
        '<div class="ar-learning-topics">',
    ]
    deep_path = PREFIX + "deep-dives/index.md"
    deep_index = [
        "Compare multiple papers around one question. Start with mechanisms, then consider trade-offs "
        "and test your understanding across papers.", "",
        "Each subtopic has one card. When a relevant paper arrives, update the comparison or conclusion and record what changed.", "",
        f"{len(dives)} deep dives · {len(cards)} topic entries", "",
    ]
    for theme in themes:
        ident, topics = theme["id"], theme["topics"]
        theme_path = f"{PREFIX}paths/{ident}/index.md"
        index += [
            '<article class="ar-learning-topic-tile">',
            f'<h2><a href="{_html("en/" + theme_path, index_path)}">{escape(theme["title"])}</a></h2>',
            f'<p>{escape(theme["intro"])}</p>',
            f'<p class="ar-learning-topic-meta">{len(topics)} subtopics · {theme["question_count"]} questions / '
            f'{sum(len(t["papers"]) for t in topics)} papers</p>',
            "<details><summary>Open subtopic question banks</summary><ul>",
        ]
        deep_index += [
            f'<details class="ar-deep-shelf"><summary>{escape(theme["title"])} · {len(topics)} cards</summary>',
            '<div class="ar-deep-grid">',
        ]
        overview = [theme["intro"], "", "Choose a subtopic and start with its paper questions.", "",
                    '<div class="ar-learning-topics">']
        for topic in topics:
            slug = topic["id"]
            path = f"{PREFIX}paths/{ident}/{slug}.md"
            dive_path = deep.page_path(ident, slug)
            dive = dives[f"{ident}/{slug}"]
            title, count = escape(topic["title"]), topic["question_count"]
            members = [by_identity[i] for i in topic["papers"]]
            index += [
                f'<li><a href="{_html("en/" + path, index_path)}">{title}</a><span>{count} questions'
                f'<a class="ar-learning-deep-link" href="{_html("en/" + dive_path, index_path)}">Deep dive</a></span></li>',
            ]
            overview += [
                '<article class="ar-learning-topic-tile">',
                f'<h2><a href="{_html("en/" + path, theme_path)}">{title}</a></h2>',
                f'<p>{escape(topic["question"])}</p>',
                f'<p class="ar-learning-topic-meta">{count} questions · {len(members)} papers</p>',
                "</article>",
            ]
            deep_index += [
                '<article class="ar-deep-tile">',
                f'<h2><a href="{_html("en/" + dive_path, deep_path)}">{escape(dive["title"])}</a></h2>',
                f'<p>{escape(dive["thesis"])}</p>',
                f'<p class="ar-learning-topic-meta">{len(dive["comparisons"])} comparison papers · '
                f'{len(dive["questions"])} cross-paper questions · {dive["updated"]}</p>', "</article>",
            ]
            output[f"docs/en/{dive_path}"] = _deep_dive(root, dive_path, topic | {"path": path}, dive, by_identity)
            body = [
                f"[{theme['title']}](index.md) / {count} questions · {len(members)} papers", "",
                "Try answering each question before opening the explanation. The bank grows as papers and questions are added.", "",
                f"[Read this topic's comparisons, analysis, and cross-paper Q&A]({_md(dive_path, path)})", "",
                browser(members, path, filters=False), "",
                '<details class="ar-learning-guide" markdown="1"><summary>Topic guide and reading order</summary>', "",
                "## Start with this question", "", topic["question"], "",
                "## Takeaway", "", topic["takeaway"], "", "## Example", "", topic["example"], "",
                "## Common pitfall", "", topic["pitfall"], "", "## Reading order", "", topic["reading_order"], "",
            ]
            for rank, identity in enumerate(topic["start_here"], 1):
                card = by_identity[identity]
                url = quote(card["paper_url"], safe=":/?&=%#@+,;~.-_")
                body.append(f"{rank}. [{_title(card['title'])}]({_md('../' + card['detail_path'], path)})"
                            f" · [{card['source_label']}]({url})")
            body += ["", "## Check your understanding", "", topic["self_test"]["question"], "",
                     '??? note "Show suggested answer"', "",
                     *["    " + line if line else "" for line in topic["self_test"]["answer"].splitlines()],
                     "", "</details>", "",
                     f"[Search all questions]({_md(PREFIX + 'all.md', path)}) · "
                     f"[Recently added]({_md(PREFIX + 'recent.md', path)})"]
            add(path, topic["title"], body)
        index += ["</ul></details></article>"]
        overview += ["</div>", "", "[All themes](../../index.md)"]
        add(theme_path, theme["title"], overview)
        deep_index += ["</div></details>", ""]
    deep_index += ["[All paper questions](../all.md) · [Learning home](../index.md)"]
    add(deep_path, "Topic deep dives", deep_index)
    index += ["</div>", "", "## Recently added", "", '<div class="ar-learning-recent"><ul>']
    for card in recent[:8]:
        question = card["questions"][0]
        link = _html("en/learning/all.md", index_path) + "#" + qa.question_anchor(card["identity"], question["id"])
        index += [f'<li><a href="{link}">{escape(question["question"])}</a>'
                  f'<span>{question["added"]} · {escape(card["key"])}</span></li>']
    index += ["</ul></div>", "", "[All recent additions](recent.md)"]
    add(index_path, "Learn the papers", index)
    return output
