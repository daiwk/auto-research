"""Build the English paper catalog and check the bilingual documentation contract."""

from __future__ import annotations

import argparse
from collections import defaultdict
from collections.abc import Set
from hashlib import sha256
from html import escape
import json
from pathlib import Path, PurePosixPath
import re
import subprocess
from urllib.parse import urlsplit


ROOT = Path(__file__).resolve().parents[1]
MANIFEST = "docs/research-manifest.json"
CATALOG = "docs/en/papers"
COVERAGE = "docs/en/coverage.md"
GUIDES = {
    "README.md": "README.en.md",
    "docs/index.md": "docs/en/index.md",
    "readme_setup.md": "docs/en/setup.md",
}
SITE_ALIASES = {"docs/readme_setup.md": "docs/en/setup.md"}
SECTIONS = {
    "recommendation": "Search, ads, recommendation, and LLM applications",
    "foundation-models": "Foundation models",
    "system-one": "Structured decisions / System One",
    "multimodal-models": "Multimodal models",
    "post-training": "LLM post-training",
    "agent-research": "Agents",
}
FINGERPRINT = re.compile(r"^<!-- source-sha256: ([a-f0-9]{64}) -->$", re.MULTILINE)
GENERATED = "<!-- Generated by scripts/english_docs.py from the research manifest. -->\n"


def paper_source(row: dict) -> str:
    path = row["detail_path"]
    if not re.fullmatch(r"[a-zA-Z0-9_./-]+/README\.md", path) or any(
        part in {"", ".", ".."} for part in path.split("/")
    ):
        raise ValueError(f"Invalid paper detail path: {path!r}")
    return f"docs/{path}"


def english_sibling(path: str) -> str:
    return str(PurePosixPath(path).with_name("README-en.md"))


def paper_pairs(rows: list[dict]) -> dict[str, str]:
    return {paper_source(row): english_sibling(paper_source(row)) for row in rows}


def site_pairs(root: Path, rows: list[dict]) -> dict[str, str]:
    """Inventory every Chinese Markdown page, not just manifest papers."""
    docs = root / "docs"
    papers = paper_pairs(rows)
    pairs = {}
    for path in sorted(docs.rglob("*.md")):
        relative = path.relative_to(docs)
        if relative.parts[0] == "en" or relative.name == "README-en.md":
            continue
        source = f"docs/{relative.as_posix()}"
        pairs[source] = (papers.get(source) or SITE_ALIASES.get(source)
                         or f"docs/en/{relative.as_posix()}")
    return pairs


def untranslated_pages(root: Path, rows: list[dict]) -> list[str]:
    return [source for source, target in site_pairs(root, rows).items()
            if not (root / target).is_file()]


def translation_errors(
    root: Path,
    rows: list[dict],
    *,
    changed: Set[str] = frozenset(),
    added_sources: Set[str] = frozenset(),
) -> list[str]:
    """Require translations of new site pages and changed papers; validate all pairs."""
    papers = paper_pairs(rows)
    guides = GUIDES | {
        source: target for source, target in site_pairs(root, rows).items()
        if source not in papers and source not in SITE_ALIASES
        and ((root / target).is_file() or target in changed or source in added_sources)
    }
    errors = []
    for source, target in sorted((guides | papers).items()):
        translation = root / target
        if not translation.is_file():
            if source in guides or source in changed or target in changed or source in added_sources:
                errors.append(f"{source}: add its English version at {target}")
            continue
        if not (root / source).is_file():
            errors.append(f"{target}: missing Chinese source {source}")
            continue
        content = translation.read_text(encoding="utf-8")
        digests = FINGERPRINT.findall(content)
        actual = sha256((root / source).read_bytes()).hexdigest()
        if digests != [actual]:
            errors.append(f"{target}: review against {source} and set source-sha256 to {actual}")
        if source in papers and not re.search(r"\[[^\n\]]+\]\(README\.md\)", content):
            errors.append(f"{target}: link back to the Chinese README.md")
    targets = set(papers.values())
    for translation in sorted((root / "docs").rglob("README-en.md")):
        if translation.relative_to(root).as_posix() not in targets:
            errors.append(f"{translation.relative_to(root)}: not paired with a catalog paper")
    return errors


def table_cell(value: str) -> str:
    # Metadata is data, not raw Markdown or HTML.
    return escape(" ".join(value.split()), quote=False).translate(
        str.maketrans({char: f"&#{ord(char)};" for char in "\\|`[]!*_"})
    )


def paper_title_link(row: dict) -> str:
    title, url = table_cell(row["title"]), row.get("paper_url")
    if isinstance(url, str):
        parts = urlsplit(url)
        if parts.scheme in {"https", "http"} and parts.netloc and not re.search(r"[\s<>]", url):
            return f"[{title}](<{url}>)"
    return title


def catalog_pages(root: Path, rows: list[dict]) -> dict[str, str]:
    grouped = defaultdict(list)
    for row in rows:
        source = paper_source(row)
        domain = "system-one" if source.startswith("docs/system-one/") else row["domain"]
        if domain not in SECTIONS:
            raise ValueError(f"Unmapped English catalog domain: {domain}")
        grouped[domain].append((row, source))
    pages = {}
    links = []
    available = []
    for domain, heading in SECTIONS.items():
        entries = sorted(grouped[domain], key=lambda pair: (pair[0].get("published") or "", pair[0]["title"]), reverse=True)
        translated = 0
        lines = [
            GENERATED.rstrip(), "", f"# {heading}", "", "[Back to the paper catalog](index.md)", "",
            "Paper titles link to the original publication when available. "
            "An English write-up is project documentation, not a claim of full reproduction.",
            "", "| Paper | First publication | Project write-up |", "| --- | --- | --- |",
        ]
        for row, source in entries:
            original = "../../" + source.removeprefix("docs/")
            target = english_sibling(source)
            if (root / target).is_file():
                translated += 1
                available.append((row, target))
                language = f"[English](../../{target.removeprefix('docs/')}) · [Chinese]({original})"
            else:
                language = f"English write-up not yet available · [Chinese]({original})"
            date = table_cell(row.get("published") or "Not recorded")
            lines.append(f"| {paper_title_link(row)} | {date} | {language} |")
        pages[f"{CATALOG}/{domain}.md"] = "\n".join(lines) + "\n"
        links.append(f"- [{heading}]({domain}.md): {len(entries)} catalog entries, {translated} English write-ups")
    index = [
        GENERATED.rstrip(), "", "# Paper catalog", "",
        "[English home](../index.md) · [中文研究库](../../research-library.md)", "",
        f"The catalog lists {len(rows)} entries from the shared research manifest. "
        f"English write-ups available: {len(available)}. For older entries without a translation, "
        "the original publication and the Chinese write-up remain available where listed.",
        "", "## Browse by domain", "", *links, "",
    ]
    if available:
        index.extend(["## Read in English", ""])
        for row, path in sorted(available, key=lambda pair: (pair[0].get("published") or "", pair[0]["title"]), reverse=True):
            index.append(f"- [{table_cell(row['title'])}](../../{path.removeprefix('docs/')})")
        index.append("")
    pages[f"{CATALOG}/index.md"] = "\n".join(index)
    return pages


def check_catalog(root: Path, rows: list[dict], *, write: bool) -> list[str]:
    errors = []
    pages = catalog_pages(root, rows) | {COVERAGE: coverage_page(root, rows)}
    for name, text in pages.items():
        path = root / name
        if write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
        elif not path.is_file() or path.read_text(encoding="utf-8") != text:
            errors.append(f"{name}: regenerate with python scripts/english_docs.py --write")
    return errors


def coverage_page(root: Path, rows: list[dict]) -> str:
    totals = defaultdict(lambda: [0, 0])
    pairs = site_pairs(root, rows)
    missing_count = 0
    for source, target in pairs.items():
        parts = PurePosixPath(source).parts
        section = parts[1] if len(parts) > 2 else "Top-level pages"
        translated = (root / target).is_file()
        totals[section][0] += 1
        totals[section][1] += translated
        missing_count += not translated
    lines = [
        "<!-- Generated by scripts/english_docs.py from the site source inventory. -->", "",
        "# English translation coverage", "",
        "[English home](index.md) · [Paper catalog](papers/index.md)", "",
        f"**{len(pairs) - missing_count} of {len(pairs)}** Chinese site pages have a corresponding English page.",
        "The table counts document pairs, not English catalog entries that link to Chinese text.", "",
        "| Source section | Pages | English counterparts | Still untranslated |",
        "| --- | ---: | ---: | ---: |",
    ]
    for section, (total, translated) in sorted(totals.items()):
        lines.append(f"| {section} | {total} | {translated} | {total - translated} |")
    return "\n".join([*lines, ""])


def changes_since(root: Path, base: str, rows: list[dict]) -> tuple[set[str], set[str]]:
    """Use the PR base tree, including new pages and newly cataloged existing prose."""
    if not re.fullmatch(r"[a-f0-9]{40}", base):
        raise ValueError("--base must be a full Git commit SHA")
    changed = subprocess.check_output(
        ["git", "diff", "--name-status", "-z", "--no-renames", "--diff-filter=ACDM", base, "--"], cwd=root,
    ).decode("utf-8").split("\0")
    statuses = dict(zip(changed[1::2], changed[::2]))
    previous = json.loads(subprocess.check_output(["git", "show", f"{base}:{MANIFEST}"], cwd=root))["papers"]
    identities = {(r["domain"], r["key"], paper_source(r)) for r in previous}
    added = {
        paper_source(row) for row in rows
        if (row["domain"], row["key"], paper_source(row)) not in identities
    }
    added.update(source for source in site_pairs(root, rows) if statuses.get(source) == "A")
    return set(statuses), added


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="regenerate the English catalog")
    parser.add_argument("--base", help="require English for new pages and papers added or edited since this commit")
    parser.add_argument("--list-untranslated", action="store_true", help="list each outstanding source path")
    parser.add_argument("--require-complete", action="store_true", help="fail if any Chinese site page lacks English")
    args = parser.parse_args()
    rows = json.loads((ROOT / MANIFEST).read_text(encoding="utf-8"))["papers"]
    changed, added = changes_since(ROOT, args.base, rows) if args.base else (set(), set())
    errors = translation_errors(ROOT, rows, changed=changed, added_sources=added)
    errors.extend(check_catalog(ROOT, rows, write=args.write))
    if args.require_complete or args.list_untranslated:
        missing = untranslated_pages(ROOT, rows)
        if args.list_untranslated:
            for source in missing:
                print(source)
        if args.require_complete and missing:
            errors.append(f"English coverage incomplete: {len(missing)} untranslated pages; first ten:")
            errors.extend(missing[:10])
    if errors:
        print("\n".join(errors))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
