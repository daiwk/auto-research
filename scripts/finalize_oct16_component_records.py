def build_records(root: Path, *, accept_gpu_evidence=False, accept_cpu_evidence=False) -> tuple[list[dict], dict]:
    old_figures = json.loads((root / FIGURES).read_text())
    old_ledger = json.loads((root / LEDGER).read_text())
    catalogs = {}
    for path in (root / "src/auto_research/paper_specs/catalog").glob("*/*.json"):
        row = json.loads(path.read_text())
        if row.get("key") in {item.key for item in SELECTED}:
            if row["key"] in catalogs:
                raise ValueError(f"duplicate selected catalog key: {row['key']}")
            catalogs[row["key"]] = row
    if set(catalogs) != {item.key for item in SELECTED}:
        raise ValueError("selected-15 catalog entries are incomplete")
    old_batch = [batch for batch in old_ledger["batches"] if batch.get("batch") == BATCH]
    if len(old_batch) > 1:
        raise ValueError("duplicate selected-15 implementation batch")
    previous = {row["key"]: row for row in old_batch[0]["candidates"]} if old_batch else {}
    candidates, additions = [], []
    for item in SELECTED:
        catalog = catalogs[item.key]
        status = catalog.get("implementation_status")
        if status not in {"component_only", "evaluation_protocol_interface"}:
            raise ValueError(f"{item.key}: invalid bounded implementation status {status}")
        if catalog.get("full_experiment_status") != "not_reproduced_high_cost":
            raise ValueError(f"{item.key}: full experiment cost decision is not terminal")
        page = "docs/" + catalog["detail_path"]
        text = (root / page).read_text()
        if item.paper_id not in text or item.asset_name not in text:
            raise ValueError(f"{item.key}: paper identity/asset missing in README")
        if not (root / item.source_file).is_file() or not (root / item.runner).is_file():
            raise ValueError(f"{item.key}: algorithm/runner source missing")
        additions.append((page, _figure(root, item, page)))
        metrics = sorted((root / page).parent.glob("metrics/*.json"))
        if item.key == "transx":
            metrics = [path for path in metrics if path.name.startswith("report-components-")]
        required = catalog.get("requires_gpu_validation") is True
        prior_pass = previous.get(item.key, {}).get("component_validation", {}).get("gpu_validation_passed") is True
        prior_cpu_pass = previous.get(item.key, {}).get("component_validation", {}).get("cpu_evidence_validated") is True
        validation = {"requires_gpu_validation": required, "gpu_validation_passed": False, "cpu_evidence_validated": False,
                      "status": "pending_root_gpu_acceptance" if required else "cpu_evidence_recorded_pending_root_acceptance",
                      "metrics": [str(path.relative_to(root)) for path in metrics]}
        if required:
            validation["gpu_validation_artifact"] = catalog.get("gpu_validation_artifact") or STANDALONE_GPU_RECEIPTS.get(catalog.get("component_key", item.key))
            if accept_gpu_evidence or prior_pass:
                if not metrics:
                    raise ValueError(f"{item.key}: GPU acceptance also requires committed component metrics")
                validation["accepted_receipt"] = validate_component_gpu(root, catalog, item)
