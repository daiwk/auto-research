def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _figure(root: Path, selected: Selected, page: str) -> dict:
    asset = str(Path(page).parent / "assets" / selected.asset_name)
    data = (root / asset).read_bytes()
    if data[:8] != b"\x89PNG\r\n\x1a\n" or len(data) < 5000:
        raise ValueError(f"invalid/unreadable original-paper image: {asset}")
    width, height = struct.unpack(">II", data[16:24])
    if width < 400 or height < 140:
        raise ValueError(f"original-paper image too small: {asset}")
    return {"paper_url": f"https://arxiv.org/abs/{selected.paper_id}", "arxiv_id": selected.paper_id,
            "figure": selected.figure, "original_caption": "", "caption_zh": selected.caption,
            "source_url": selected.source_url,
            "extraction": "pdf-page-crop" if "/pdf/" in selected.source_url else "official-original-asset",
            "asset": asset, "asset_sha256": hashlib.sha256(data).hexdigest(),
            "width": width, "height": height, "score": 0, "error": ""}


def merge_figures(existing: list[dict], additions: list[tuple[str, dict]]) -> list[dict]:
    result = deepcopy(existing)
    by_page = {row["page"]: row for row in result}
    if len(by_page) != len(result):
        raise ValueError("existing figure manifest has duplicate pages")
    for page, figure in additions:
        if page not in by_page:
            row = {"page": page, **figure}
            result.append(row)
            by_page[page] = row
        elif by_page[page].get("asset") == figure["asset"]:
            by_page[page].update(figure)
        else:
            # A new report must not replace the historic paper's primary image.
            supplements = by_page[page].setdefault("supplementary_figures", [])
            matches = [row for row in supplements if row.get("asset") == figure["asset"]]
            if len(matches) > 1:
                raise ValueError("duplicate supplementary figure asset")
            if matches:
                matches[0].update(figure)
            else:
                supplements.append(figure)
    return result


def validate_component_gpu(root: Path, catalog: dict, selected: Selected) -> dict:
    component_key = catalog.get("component_key", selected.key)
    artifact = catalog.get("gpu_validation_artifact") or STANDALONE_GPU_RECEIPTS.get(component_key)
    if not artifact:
        raise ValueError(f"{selected.key}: missing declared component receipt path")
    path = (root / artifact).resolve()
    if not path.is_relative_to(root.resolve()) or not path.is_file():
        raise ValueError(f"{selected.key}: GPU receipt missing or outside repository: {artifact}")
    receipt = load_gpu_receipt(path)
    if receipt["adapter_key"] != component_key or receipt["provenance"]["artifact_path"] != artifact:
        raise ValueError(f"{selected.key}: wrong component receipt identity/path")
    if not any(model in receipt["accelerator"]["model"].upper() for model in ("A100", "A30")):
        raise ValueError(f"{selected.key}: selected gate requires A100 or A30")
    hashes = receipt.get("executed_source_sha256") or receipt["provenance"].get("executed_source_sha256")
    if not isinstance(hashes, dict) or not hashes:
        raise ValueError(f"{selected.key}: receipt lacks executed_source_sha256 dictionary")
    if not {selected.source_file, selected.runner} <= set(hashes):
        raise ValueError(f"{selected.key}: executed hashes do not cover algorithm and runner")
    for name, digest in hashes.items():
        source = (root / name).resolve()
        if not source.is_relative_to(root.resolve()) or not source.is_file() or not re.fullmatch(r"[0-9a-f]{64}", digest):
            raise ValueError(f"{selected.key}: invalid source binding {name}")
        if _sha(source) != digest:
            raise ValueError(f"{selected.key}: executed source hash differs: {name}")
    return {"artifact": artifact, "sha256": _sha(path), "adapter_key": component_key,
            "accelerator": receipt["accelerator"]["model"], "code_commit": receipt["provenance"]["commit"],
            "source_hashes_verified": len(hashes)}


