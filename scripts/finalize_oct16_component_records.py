        for name, digest in expected.items():
            if not (directory / name).is_file() or _sha(directory / name) != digest:
                raise ValueError(f"{selected.key}: official CPU input missing/changed: {name}")
        input_fingerprints = expected
        module_name = selected.source_file.removeprefix("src/").removesuffix(".py").replace("/", ".")
        module = importlib.import_module(module_name)
