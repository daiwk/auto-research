def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--accept-gpu-evidence", action="store_true")
    parser.add_argument("--accept-cpu-evidence", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    figures, ledger = build_records(ROOT, accept_gpu_evidence=args.accept_gpu_evidence,
                                   accept_cpu_evidence=args.accept_cpu_evidence)
    changed = []
    for relative, payload in ((FIGURES, figures), (LEDGER, ledger)):
        path = ROOT / relative
        rendered = json.dumps(payload, ensure_ascii=False, indent=2) + "\n"
        if rendered != path.read_text():
            changed.append(relative)
            if not args.check:
                path.write_text(rendered)
    print(json.dumps({"selected": 15, "changed": changed, "check": args.check,
                      "watermark_advanced": False, "old_review_batches_modified": False}))
    return int(args.check and bool(changed))


