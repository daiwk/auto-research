"""Mirror the repository README into the MkDocs site with site-safe links."""

from __future__ import annotations

import argparse
from pathlib import Path, PurePosixPath
import re
from urllib.parse import urlsplit, urlunsplit


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "README.md"
TARGET = ROOT / "docs" / "project-readme.md"
NOTICE = "<!-- Generated by scripts/sync_project_readme.py; edit README.md instead. -->\n\n"
COUNT_PATTERN = re.compile(r"仓库目前注册 \*\*\d+ 个\*\*论文 adapter")


def normalized_source(source: Path | None = None) -> str:
    source = source or SOURCE
    content = source.read_text(encoding="utf-8")
    specifications = list(
        (ROOT / "src" / "auto_research" / "reproductions").glob("*/paper.yaml")
    )
    replacement = f"仓库目前注册 **{len(specifications)} 个**论文 adapter"
    if source == SOURCE and not COUNT_PATTERN.search(content):
        raise SystemExit("README.md is missing the generated adapter-count sentence")
    return COUNT_PATTERN.sub(replacement, content)


def site_link(value: str) -> str:
    parts = urlsplit(value)
    if parts.scheme or parts.netloc or not parts.path:
        return value
    path = parts.path
    if path.startswith("docs/"):
        path = path.removeprefix("docs/")
    elif path == "README.md":
        path = "project-readme.md"
    elif not (path.startswith("readme_") and path.endswith(".md")):
        # Root source files are not copied into the documentation tree.
        kind = "tree" if (ROOT / path).is_dir() else "blob"
        path = f"https://github.com/daiwk/auto-research/{kind}/main/{path}"
    return urlunsplit(parts._replace(path=path))


def site_html_link(value: str) -> str:
    """Raw HTML bypasses MkDocs' Markdown link rewriting on directory pages."""
    rewritten = site_link(value)
    parts = urlsplit(rewritten)
    if parts.scheme or parts.netloc or not parts.path:
        return rewritten
    path = PurePosixPath(parts.path)
    if path.suffix.lower() == ".md":
        route = path.parent if path.name.lower() in {"readme.md", "index.md"} else path.with_suffix("")
        target = "" if route == PurePosixPath(".") else str(route) + "/"
    else:
        target = parts.path
    # All mirrored root READMEs become one-level directory URLs in this site.
    return urlunsplit(parts._replace(path="../" + target))


def rendered(source: Path | None = None) -> str:
    source = source or SOURCE
    content = normalized_source(source)
    content = re.sub(r"(\]\()([^\s)]+)(\))", lambda m: m[1] + site_link(m[2]) + m[3], content)
    content = re.sub(r'(\b(?:href|src|srcset)=")([^"]+)(")',
                     lambda m: m[1] + site_html_link(m[2]) + m[3], content)
    notice = NOTICE if source == SOURCE else f"<!-- Generated by scripts/sync_project_readme.py; edit {source.name} instead. -->\n\n"
    return notice + content


def sources() -> list[Path]:
    return [SOURCE, *sorted(ROOT.glob("readme_*.md"))]


def target_for(source: Path) -> Path:
    return TARGET if source == SOURCE else ROOT / "docs" / source.name


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for source in sources():
        expected = rendered(source)
        target = target_for(source)
        if args.check:
            if source.read_text(encoding="utf-8") != normalized_source(source):
                raise SystemExit(f"{source.name} adapter count is stale; run python scripts/sync_project_readme.py")
            if not target.exists() or target.read_text(encoding="utf-8") != expected:
                raise SystemExit(f"{target} is stale; run python scripts/sync_project_readme.py")
        else:
            source.write_text(normalized_source(source), encoding="utf-8")
            target.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
