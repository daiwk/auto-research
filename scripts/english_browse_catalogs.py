def _entry(row: Mapping, original: str, source: str) -> str:
    key = f"`{row['key']}`"
    if original.startswith("计划键 "):
        return f"Planned key {key} — {_status(row)}"
    if original in _ENTRY_NOTES:
        return _ENTRY_NOTES[original]
    if original.startswith(f"{key}："):
        note = original.removeprefix(f"{key}：")
        if note not in _ENTRY_NOTES:
            raise ValueError(f"{source}: add a reviewed local entry note for {note!r}")
        return f"{key} — {_ENTRY_NOTES[note]}"
    return _translate(original, source)


def _paper_table(
    line: str, match: re.Match, row: Mapping, text: str, source: str, destination: str,
) -> str:
    cells = _cells(line)
    topic, label = _translate(cells[0], source), _paper_link(match, row, source, destination)
    if len(cells) == 6 and source == "docs/system-one/catalog.md":
        return _table([
            topic, label, _translate(cells[2], source), cells[3],
            _inline(_summary(text, row["source"])), _translate(cells[5], source),
        ])
    institution, delimiter, date = cells[2].rpartition("，")
    if not delimiter or len(cells) not in {4, 5}:
        raise ValueError(f"{source}: unrecognized paper table row for {row['source']}")
    info = f"{_plain_markdown(_translate(institution, source))}, {_translate(date, source)}"
    entry = _entry(row, cells[-1], source)
    if len(cells) == 4:
        return _table([topic, label, info, entry])
    return _table([topic, label, info, _code_cell(text, row, cells[3], destination), entry])


def _nonpaper(line: str, source: str, destination: str) -> str:
    if line in _PROSE:
        line = _PROSE[line]
    if line.startswith("    ") and line.strip() in _PROSE:
        return "    " + _PROSE[line.strip()]
    if line.startswith("分类浏览："):
        line = "Browse by: " + line.removeprefix("分类浏览：")
    if line.startswith("|"):
        cells = _cells(line)
        if all(re.fullmatch(r":?-+:?", cell) for cell in cells):
            return line
        return _table([_nonpaper(cell, source, destination) for cell in cells])
    line = _LINK.sub(
        lambda m: f"[{_translate(m[1], source)}]({_route_link(source, destination, m[2])})",
        line,
    )
    return _translate(line, source)


def catalog_pages(
    root: Path, rows: list[dict], *, pairs: Mapping[str, str] = CATALOG_PAIRS,
) -> dict[str, str]:
    """Return all English browse pages as a single pure, fail-closed operation."""
    papers = {
        f"docs/{row['detail_path']}": {**row, "source": f"docs/{row['detail_path']}"}
        for row in rows
    }
    outputs, reviewed = {}, {}
    for source, destination in pairs.items():
        source_bytes = (root / source).read_bytes()
        digest = sha256(source_bytes).hexdigest()
        lines = [_GENERATED, f"<!-- source-sha256: {digest} -->", ""]
        for number, line in enumerate(source_bytes.decode("utf-8").splitlines(), 1):
            heading = _HEADING.fullmatch(line)
            if heading:
                lines.append(f"{heading[1]} {_translate(heading[2], source)}")
                if heading[1] == "#":
                    lines.extend(["", f"[简体中文]({_relative(source, destination)}) · English"])
                continue
            paper = _find_paper(line, source, papers) if line.startswith(("- ", "|")) else None
            if paper:
                match, row = paper
                path = row["source"]
                if path not in reviewed:
                    reviewed[path] = _reviewed_page(root, path)
                render = _paper_table if line.startswith("|") else _paper_bullet
                lines.append(render(line, match, row, reviewed[path], source, destination))
                continue
            try:
                lines.append(_nonpaper(line, source, destination))
            except ValueError as error:
                raise ValueError(f"{source}:{number}: {error}") from error
        outputs[destination] = "\n".join(lines).rstrip() + "\n"
    return outputs
