def _translate(text: str, context: str) -> str:
    translated = _LABELS.get(text, text)
    if _CJK.search(translated):
        raise ValueError(f"{context}: add a reviewed English label for {text!r}")
    return translated


def _plain_markdown(text: str) -> str:
    """Make inline data safe in titles and table cells without double HTML escaping."""
    return escape(text, quote=False).translate(
        str.maketrans({char: f"&#{ord(char)};" for char in "\\|`[]!*_"})
    )


def _inline(text: str) -> str:
    return text.replace("|", "&#124;")


def _relative(target: str, destination: str) -> str:
    return relpath(target, PurePosixPath(destination).parent.as_posix())


def _resolve(source: str, href: str) -> str:
    path = normpath(str(PurePosixPath(source).parent / href))
    if not path.startswith("docs/"):
        raise ValueError(f"{source}: catalog link escapes docs: {href!r}")
    return path


def _http_url(value: object) -> bool:
    if not isinstance(value, str) or re.search(r"[\s<>]", value):
        return False
    url = urlsplit(value)
    return url.scheme in {"http", "https"} and bool(url.netloc)


def _summary(text: str, context: str) -> str:
    # Do not invent a synopsis or fall back to Chinese metadata if the reviewed
    # page lacks recognizable method prose.
    lines = text.splitlines()
    for heading in (_METHOD_HEADING, _ORIGINAL_HEADING):
        for start, line in enumerate(lines):
            if not heading.fullmatch(line):
                continue
            paragraphs: list[str] = []
            paragraph: list[str] = []
            for entry in lines[start + 1:]:
                entry = entry.strip()
                if entry.startswith(("#", "<!--", "```", "~~~", "$$", "|", "- ", ">", "![")):
                    break
                if entry:
                    paragraph.append(entry)
                elif paragraph:
                    paragraphs.append(" ".join(paragraph))
                    paragraph.clear()
                    if len(paragraphs) == 2:
                        break
            if paragraph:
                paragraphs.append(" ".join(paragraph))
            if not paragraphs:
                continue
            # The first paragraph often explains the problem and the second
            # introduces the contribution. Prefer the latter when it is still
            # method prose, not a local diagnostic or a figure introduction.
            chosen = paragraphs[0]
            if len(paragraphs) == 2 and not re.match(
                r"(?:The |This )?(?:local|figure|diagram|illustration|implementation here)\b",
                paragraphs[1], re.IGNORECASE,
            ):
                chosen = paragraphs[1]
            # Preserve reference labels without copying relative write-up links.
            joined = _LINK.sub(r"\1", chosen)
            sentences = re.split(r"(?<=[.!?])\s+(?=[A-Z])", joined)
            return _translate(" ".join(sentences[-2:] if chosen == paragraphs[0] else sentences[:2]), context)
    raise ValueError(f"{context}: reviewed English page needs a method paragraph")


def _reviewed_page(root: Path, source: str) -> str:
    target = str(PurePosixPath(source).with_name("README-en.md"))
    path = root / target
    if not path.is_file():
        raise ValueError(f"{target}: reviewed English write-up required for the browse catalog")
    text = path.read_text(encoding="utf-8")
    digest = sha256((root / source).read_bytes()).hexdigest()
    if _HASH.findall(text) != [digest] or "[简体中文](README.md)" not in text:
        raise ValueError(f"{target}: stale or unpaired English write-up")
    return text


def _author_text(text: str, context: str) -> str:
    text = text.replace("（共同一作，随机排序）", " (co-first authors, randomized order)")
    text = text.replace("（共同一作）", " (co-first authors)")
    text = re.sub(
        r"（共同一作：([^）]+)）",
        lambda m: f" (co-first author(s): {m[1].replace('、', ', ')})",
        text,
    )
    return _translate(text, context)


def _browse_prefix(prefix: str, context: str) -> str:
    prefix = prefix.replace("- 未标注", "- Not recorded", 1)
    if "一作：" in prefix:
        date, author = prefix.removesuffix(" · ").split(" · 一作：", 1)
        return f"{_translate(date, context)} · First author: {_author_text(author, context)} · "
    return _translate(prefix, context)


def _status(row: Mapping) -> str:
    kind = row.get("implementation_status")
    if kind == "deferred_high_cost":
        return (
            "Not reproduced due to cost (review complete); research material only, no executable entry."
            if row.get("review_done") is True
            else "Not reproduced for now due to cost; validation pending, no executable entry."
        )
    if kind == "evaluation_protocol_interface":
        return "Evaluation protocol interface; not a model capability result."
    if kind in {"component_only", "cpu_core_operator_diagnostic"}:
        return "Bounded component only; full experiments are not reproduced."
    if kind == "checkpoint_inference":
        return "Checkpoint inference; not a reproduction of training."
    if kind is not None:
        raise ValueError(f"{row['source']}: unknown implementation status {kind!r}")
    return ""


def _route_link(source: str, destination: str, href: str) -> str:
    if _http_url(href) or href.startswith("#"):
        return href
    parts = urlsplit(href)
    if parts.scheme or parts.netloc or parts.query or not parts.path.endswith(".md"):
        raise ValueError(f"{source}: unrecognized catalog link: {href!r}")
    page = _resolve(source, parts.path)
    target = CATALOG_PAIRS.get(page, f"docs/en/{page.removeprefix('docs/')}")
    result = _relative(target, destination)
    return f"{result}#{parts.fragment}" if parts.fragment else result


def _more_links(line: str, original: re.Match, context: str) -> str:
    # A handful of catalog blurbs cite an exact section of the primary paper.
    # Preserve those links even when the English synopsis uses different prose.
    urls = []
    for match in _LINK.finditer(line):
        if match.span() == original.span():
            continue
        if not _http_url(match[2]):
            raise ValueError(f"{context}: unexpected extra paper-row link: {match[2]!r}")
        if match[2] not in urls:
            urls.append(match[2])
    return "".join(f" [Method reference {i}](<{url}>)" for i, url in enumerate(urls, 1))


def _code_cell(text: str, row: Mapping, source_cell: str, destination: str) -> str:
    context = row["source"]
    match = _CODE_FIELD.search(text)
    if match:
        evidence = _translate(match[1], context)
    elif row.get("code_status") or row.get("code_license") or row.get("code"):
        raise ValueError(f"{context}: reviewed English page needs author-code provenance")
    else:
        evidence = "No official code found."

    def relink(link: re.Match) -> str:
        href = link[2]
        if _http_url(href):
            return link[0]
        parts = urlsplit(href)
        if parts.scheme or parts.netloc:
            raise ValueError(f"{context}: invalid author-code evidence link: {href!r}")
        source = _resolve(context, parts.path) if parts.path else context
        relocated = _relative(source, destination)
        if parts.query:
            relocated += f"?{parts.query}"
        if parts.fragment:
            relocated += f"#{parts.fragment}"
        return f"[{link[1]}]({relocated})"

    evidence = _LINK.sub(relink, evidence)
    # Keep linked data or projects in the original catalog without inferring that
    # any linked URL is a released source repository.
    for url in dict.fromkeys(_URL.findall(source_cell)):
        if _http_url(url) and url not in evidence:
            evidence += f" [Author resource](<{url}>)."
    return _inline(evidence)


def _paper_link(match: re.Match, row: Mapping, source: str, destination: str) -> str:
    label = match[1] if not _CJK.search(match[1]) else row["title"]
    escaped = _plain_markdown(_translate(label, source))
    target = str(PurePosixPath(row["source"]).with_name("README-en.md"))
    return f"[{escaped}]({_relative(target, destination)})"


def _find_paper(line: str, source: str, papers: Mapping) -> tuple[re.Match, Mapping] | None:
    for match in _LINK.finditer(line):
        href = match[2]
        if href.endswith("/README.md") and not _http_url(href):
            key = _resolve(source, href)
            if key not in papers:
                raise ValueError(f"{source}: catalog paper is not in the manifest: {key}")
            return match, papers[key]
    return None


def _paper_bullet(
    line: str, match: re.Match, row: Mapping, text: str, source: str, destination: str,
) -> str:
    prefix = _browse_prefix(line[:match.start()], source)
    suffix = line[match.end():]
    # Retain metadata displayed by the original page, including the System One
    # date and named author and the adapter suffix in three standard views.
    after = re.match(r"^（([^）]+)）", suffix)
    if not after:
        metadata = ""
    elif after[1].startswith("`"):
        metadata = f" ({_translate(after[1], source)})"
    else:
        metadata = f" ({_author_text(after[1].replace('，一作', ', first author '), source)})"
    summary = _summary(text, row["source"])
    status = _status(row)
    tail = _more_links(line, match, source)
    status_label = f" **{status}**" if status else ""
    return f"{prefix}{_paper_link(match, row, source, destination)}{metadata}: {summary}{status_label}{tail}"


def _cells(line: str) -> list[str]:
    return [cell.strip() for cell in re.split(r"(?<!\\)\|", line.strip()[1:-1])]


def _table(cells: list[str]) -> str:
    return "| " + " | ".join(cells) + " |"


