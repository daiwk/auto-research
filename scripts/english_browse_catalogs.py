def _label_map(raw: str) -> dict[str, str]:
    result = {}
    for line in raw.strip().splitlines():
        zh, en = line.split(" = ", 1)
        if zh in result:
            raise ValueError(f"Duplicate English catalog label: {zh}")
        result[zh] = en
    return result


