"""Lossless log and bounded grep tool, arXiv:2611.25123v1 §3 / Appendix B.

L1 memory substrate only. Summaries are explicit caller inputs, not generated by
a fake LLM. A fresh regex worker enforces the paper's ten-second search bound;
patterns are data, never shell commands. No disk, model, gold or embedding access.
"""

from __future__ import annotations

from dataclasses import dataclass
import json
import subprocess
import sys

REQUIRES_GPU_VALIDATION = False

_WORKER = r'''
import json,re,sys
p=json.load(sys.stdin)
try:
    regex=re.compile(p["pattern"],re.IGNORECASE)
except re.error as e:
    print(json.dumps({"error":str(e)}));sys.exit(0)
total=0; counts={}; selected=[]
for ri,record in enumerate(p["records"]):
    if record["grep_output"]:continue
    lines=record["text"].splitlines()
    for li,line in enumerate(lines):
        m=regex.search(line)
        if m is None:continue
        counts[record["kind"]]=counts.get(record["kind"],0)+1
        if not p["count"] and p["offset"]<=total<p["offset"]+p["max_matches"]:
            window=[]
            for j in range(max(0,li-p["context_lines"]),min(len(lines),li+p["context_lines"]+1)):
                start=max(0,m.start()-max(0,(300-min(300,m.end()-m.start()))//2)) if j==li else 0
                window.append({"line":j+1,"text":lines[j][start:start+300],"match":j==li})
            selected.append({"record":ri,"header":record["header"],"lines":window})
        total+=1
print(json.dumps({"total_matches":total,"counts_by_source":counts,"selected":selected}))
'''


@dataclass(frozen=True)
class Record:
    kind: str
    header: str
    text: str
    grep_output: bool = False


def _render(total: int, counts: dict, selected: list[dict]) -> str:
    result = [f"Matching lines: {total}; by source: {json.dumps(counts, sort_keys=True)}"]
    grouped: dict[int, dict] = {}
    for hit in selected:
        group = grouped.setdefault(hit["record"], {"header": hit["header"], "lines": {}})
        for row in hit["lines"]:
            old = group["lines"].get(row["line"])
            if old is None or row["match"]:
                group["lines"][row["line"]] = row
    for group in grouped.values():
        result.append(group["header"])
        previous = None
        for number, row in sorted(group["lines"].items()):
            if previous is not None and number > previous + 1:
                result.append("--")
            result.append(f"{number}{':' if row['match'] else '-'} {row['text']}")
            previous = number
    return "\n".join(result)


class GrepMemory:
    def __init__(self, system_prompt: str, task: str):
        self.records: list[Record] = []
        self.working_context: list[Record] = []
        self.enabled = False
        self.append("system", "[system]", system_prompt)
        self.append("user", "[task]", task)
        self._initial = tuple(self.working_context)

    def append(self, kind: str, header: str, text: str, *, tool_name: str | None = None) -> None:
        if kind not in {"system", "user", "assistant", "tool", "summary"}:
            raise ValueError("known interaction kind required")
        if not isinstance(header, str) or not header or "\n" in header or len(header) > 300:
            raise ValueError("single-line record header up to 300 characters required")
        if not isinstance(text, str):
            raise TypeError("record text must be a string")
        if tool_name is not None and (kind != "tool" or not isinstance(tool_name, str)):
            raise ValueError("tool_name belongs only to a tool output")
        record = Record(kind, header, text, tool_name == "grep_history")
        self.records.append(record)
        self.working_context.append(record)

    def compact(self, summary: str) -> None:
        self.append("summary", f"[summary {sum(r.kind == 'summary' for r in self.records)+1}]", summary)
        self.working_context = [*self._initial, self.records[-1]]
        self.enabled = True

    def export_log(self) -> str:
        return "\n".join(f"{r.header}\n{r.text}" for r in self.records)

    def grep(self, pattern: str, *, max_matches: int = 10, offset: int = 0,
             context_lines: int = 1, count: bool = False, timeout_seconds: float = 10) -> dict:
        if not self.enabled:
            raise RuntimeError("grep_history is unavailable before the first compaction")
        if not isinstance(pattern, str):
            raise TypeError("regular-expression string required")
        if type(max_matches) is not int or not 1 <= max_matches <= 30:
            raise ValueError("max_matches must be an integer in [1,30]")
        if type(offset) is not int or offset < 0 or type(context_lines) is not int or not 0 <= context_lines <= 3:
            raise ValueError("nonnegative match offset and context_lines in [0,3] required")
        if type(count) is not bool or isinstance(timeout_seconds, bool) or not 0 < timeout_seconds <= 10:
            raise ValueError("strict count flag and timeout in (0,10] required")
        payload = {"pattern": pattern, "max_matches": max_matches, "offset": offset,
                   "context_lines": context_lines, "count": count,
                   "records": [vars(r) for r in self.records]}
        try:
            output = subprocess.run([sys.executable, "-c", _WORKER], input=json.dumps(payload),
                                    capture_output=True, text=True, timeout=timeout_seconds,
                                    check=True)
        except subprocess.TimeoutExpired:
            return {"error": "grep search exceeded timeout", "timed_out": True}
        result = json.loads(output.stdout)
        if "error" in result:
            return result
        accepted: list[dict] = []
        total, counts = result["total_matches"], result["counts_by_source"]
        for hit in result["selected"]:
            candidate = [*accepted, hit]
            rendered = _render(total, counts, candidate)
            next_offset = offset + len(candidate)
            suffix = f"\nNext offset: {next_offset}" if next_offset < total else ""
            if len(rendered + suffix) > 6000:
                break
            accepted = candidate
        next_offset = offset + len(accepted)
        more = not count and next_offset < total
        text = _render(total, counts, accepted)
        if more:
            text += f"\nNext offset: {next_offset}"
        return {"text": text, "total_matches": total, "counts_by_source": counts,
                "returned_matches": len(accepted), "next_offset": next_offset if more else None,
                "count_only": count, "output_characters": len(text)}


def diagnostic(seed: int, device: str = "cpu") -> dict:
    if type(seed) is not int or device != "cpu":
        raise ValueError("integer seed and CPU required")
    memory = GrepMemory("Use only observed public facts.", "Recall record IDs.")
    memory.append("tool", "[turn 1 tool read]", f"record-{seed}: Alpha\nrecord-{seed+1}: Beta")
    before = memory.export_log()
    memory.compact("Two records were observed; exact IDs omitted.")
    compacted_context_omits_details = not any(
        "Alpha" in record.text or "Beta" in record.text for record in memory.working_context
    )
    first = memory.grep("alpha|beta", max_matches=1, context_lines=0)
    memory.append("tool", "[turn 2 tool grep_history]", first["text"], tool_name="grep_history")
    second = memory.grep("ALPHA|BETA", offset=1, max_matches=1, context_lines=0)
    count = memory.grep("alpha|beta", count=True)
    return {"seed": seed, "diagnostic_only": True, "evaluation_tier": "l1_mechanism",
            "checks": {"compaction_keeps_original_log": memory.export_log().startswith(before),
                       "compacted_context_omits_details": compacted_context_omits_details,
                       "regex_is_case_insensitive": second["total_matches"] == 2,
                       "prior_grep_outputs_excluded": count["total_matches"] == 2,
                       "pagination_uses_matches_not_records": first["next_offset"] == 1 and second["next_offset"] is None,
                       "outputs_bounded": first["output_characters"] <= 6000},
            "metrics": {"controlled_matching_lines": count["total_matches"],
                        "controlled_page_matches": first["returned_matches"]}}
