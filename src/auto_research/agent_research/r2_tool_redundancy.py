"""CPU L1 VFD and RA-GRPO formulas, arXiv:2611.27070v1 Eq.2--10/C.3.

Caller-supplied same-text log probabilities are not generated by this module.
No visual tool agent, crop scorer, language-model policy or gold answer access
is implemented. The numerical objective is not an RL capability experiment.
"""
from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
import math

import numpy as np

REQUIRES_GPU_VALIDATION = False
CATEGORIES = frozenset(("Tool-Independent", "Tool-Beneficial", "Challenging", "Tool-Harmful", "Ambiguous"))


def _array(value, ndim: int) -> np.ndarray:
    result = np.asarray(value, dtype=np.float64)
    if result.ndim != ndim or not result.size or not np.isfinite(result).all():
        raise ValueError("nonempty finite array of the required rank expected")
    return result


def _finite(value) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool) and math.isfinite(value)


def visual_feedback_dependency(actual_log_probabilities, alternative_log_probabilities) -> float:
    """Eq.2/3: mean log p of the SAME window under actual vs alternative view.

    Inputs must use identical token positions/context except the current tool
    feedback. This semantic condition belongs to the caller; arrays alone do
    not prove it. No answer or target label is accepted by this interface.
    """
    actual, alternatives = _array(actual_log_probabilities, 1), _array(alternative_log_probabilities, 2)
    if alternatives.shape[1] != len(actual) or np.any(actual > 0) or np.any(alternatives > 0):
        raise ValueError("aligned nonpositive same-window log probabilities required")
    value = float(actual.mean() - alternatives.mean(axis=1).mean())
    if not math.isfinite(value):
        raise ValueError("VFD overflow")
    return value


@dataclass(frozen=True)
class WarmupWindow:
    source: str
    score: float
    reasoning: bool = True


@dataclass(frozen=True)
class FrozenThresholds:
    """Explicit calibration output, immutable after warmup; no test updates."""
    values: tuple[tuple[str, float], ...]
    quantile: float = .3

    def __post_init__(self):
        if not isinstance(self.values, tuple) or not self.values or not _finite(self.quantile) or not 0 <= self.quantile <= 1:
            raise ValueError("immutable nonempty threshold tuple and valid quantile required")
        names = set()
        for pair in self.values:
            if not isinstance(pair, tuple) or len(pair) != 2:
                raise ValueError("named threshold pairs required")
            name, value = pair
            if not isinstance(name, str) or not name or name in names or not _finite(value):
                raise ValueError("unique nonempty sources and finite thresholds required")
            names.add(name)

    def for_source(self, source: str) -> float:
        for name, value in self.values:
            if name == source:
                return value
        raise ValueError("source has no reasoning-only warmup threshold")


def calibrate_thresholds(windows: Sequence[WarmupWindow], *, quantile: float = .3) -> FrozenThresholds:
    if not _finite(quantile) or not 0 <= quantile <= 1 or not windows:
        raise ValueError("nonempty explicit warmup windows and valid quantile required")
    groups: dict[str, list[float]] = {}
    for window in windows:
        if (not isinstance(window, WarmupWindow) or not isinstance(window.source, str)
                or not window.source or not _finite(window.score) or not isinstance(window.reasoning, bool)):
            raise ValueError("valid named warmup windows required")
        if window.reasoning:
            groups.setdefault(window.source, []).append(window.score)
    if not groups:
        raise ValueError("answer windows cannot initialize thresholds")
    # Linear quantile interpolation is an explicit local convention: the paper
    # specifies the 30th percentile, but not its finite-sample interpolation.
    return FrozenThresholds(tuple((source, float(np.quantile(values, quantile, method="linear")))
                                  for source, values in sorted(groups.items())), quantile)


def trajectory_cost(eligible_scores: Sequence[float | None], *, total_calls: int,
                    category: str, threshold: float, seed: int,
                    base_cost: float = .5) -> tuple[float, int | None]:
    """Eq.5/6: sample one eligible complete call, M*z, plus CAT base cost.

    Failed/incomplete calls must be excluded by the caller. None means an
    otherwise eligible complete call has unavailable VFD: C.3 assigns z=1.
    The total call count still includes unsuccessful calls for the base term.
    """
    if (not isinstance(total_calls, int) or isinstance(total_calls, bool) or total_calls < 0
            or total_calls > 10000 or len(eligible_scores) > total_calls
            or category not in CATEGORIES or not _finite(threshold)
            or not _finite(base_cost) or base_cost < 0
            or not isinstance(seed, int) or isinstance(seed, bool) or seed < 0):
        raise ValueError("valid counts, category, threshold, base cost and seed required")
    if any(score is not None and not _finite(score) for score in eligible_scores):
        raise ValueError("eligible scores must be finite or explicitly unavailable")
    selected = None
    redundant = 0
    if eligible_scores:
        selected = int(np.random.default_rng(seed).integers(len(eligible_scores)))
        score = eligible_scores[selected]
        redundant = len(eligible_scores) * int(score is None or score < threshold)
    result = redundant + base_cost * (category == "Tool-Independent") * total_calls
    if not math.isfinite(result):
        raise ValueError("trajectory cost overflow")
    return float(result), selected


def redundancy_aware_advantages(rewards, costs, *, call_budget: int = 4,
                                beta: float = .2, epsilon: float = 1e-8) -> dict[str, np.ndarray]:
    """Eq.1/7/8; sample SD for outcome and fixed budget for efficiency."""
    r, c = _array(rewards, 1), _array(costs, 1)
    if (r.shape != c.shape or len(r) < 2 or not np.isin(r, (0, 1)).all() or np.any(c < 0)
            or not isinstance(call_budget, int) or isinstance(call_budget, bool) or call_budget < 1
            or not _finite(beta) or beta < 0 or not _finite(epsilon) or epsilon <= 0):
        raise ValueError("binary group rewards, nonnegative costs and valid constants required")
    outcome = (r - r.mean()) / (r.std(ddof=1) + epsilon)
    efficiency = np.zeros_like(c)
    correct = r == 1
    if correct.any():
        efficiency[correct] = (c[correct].mean() - c[correct]) / call_budget
    with np.errstate(over="ignore", invalid="ignore"):
        combined = outcome + beta * efficiency
    if not np.isfinite(combined).all():
        raise ValueError("advantage overflow")
    return {"outcome": outcome, "efficiency": efficiency, "combined": combined}


def clipped_objective(ratios, advantages, *, mask=None, clip_epsilon: float = .2) -> float:
    """Eq.10 empirical mean: mean valid tokens per trajectory, then group mean.

    Masked tokens contribute nothing. The scalar takes ratios as explicit
    inputs; it does not compute a policy or claim that training occurred.
    """
    ratio, advantage = _array(ratios, 2), _array(advantages, 1)
    if len(advantage) != len(ratio) or np.any(ratio < 0) or not _finite(clip_epsilon) or not 0 < clip_epsilon < 1:
        raise ValueError("aligned nonnegative ratios and clip in (0,1) required")
    valid = np.ones_like(ratio, dtype=bool) if mask is None else np.asarray(mask)
    if valid.dtype != np.bool_ or valid.shape != ratio.shape or not valid.any(axis=1).all():
        raise ValueError("boolean mask with at least one generated token per trajectory required")
    try:
        with np.errstate(over="raise", invalid="raise"):
            safe_ratio = np.where(valid, ratio, 0)
            terms = np.minimum(safe_ratio * advantage[:, None],
                               np.clip(safe_ratio, 1 - clip_epsilon, 1 + clip_epsilon) * advantage[:, None])
    except FloatingPointError as exc:
        raise ValueError("objective intermediate overflow") from exc
    if not np.isfinite(terms[valid]).all():
        raise ValueError("objective overflow")
    value = float(np.mean(np.where(valid, terms, 0).sum(axis=1) / valid.sum(axis=1)))
    if not math.isfinite(value):
        raise ValueError("objective aggregation overflow")
    return value


def diagnostic(seed: int = 42, device: str = "cpu") -> dict:
    if device != "cpu":
        raise ValueError("CPU-only component; no CUDA path advertised")
    threshold = calibrate_thresholds([WarmupWindow("train-a", x) for x in (.1, .2, .4, .8)]
                                    + [WarmupWindow("train-a", -100, False)]).for_source("train-a")
    score = visual_feedback_dependency([-.2, -.4], [[-.8, -.6], [-.6, -.8], [-.7, -.7]])
    cost, selected = trajectory_cost([.1, .5, None], total_calls=4,
                                    category="Tool-Independent", threshold=threshold, seed=seed)
    advantages = redundancy_aware_advantages([1, 1, 0, 0], [0, 4, 0, 0])
    ratios = np.ones((4, 2))
    h = 1e-6
    plus, minus = ratios.copy(), ratios.copy()
    plus[0, 0] += h
    minus[0, 0] -= h
    derivative = (clipped_objective(plus, advantages["combined"])
                  - clipped_objective(minus, advantages["combined"])) / (2 * h)
    checks = {
        "vfd_same_window_difference": math.isclose(score, .4),
        "reasoning_only_threshold": math.isclose(threshold, .19),
        "single_uniform_eligible_call": selected in (0, 1, 2) and cost in (2., 5.),
        "failed_trajectories_no_efficiency_reward": bool(np.all(advantages["efficiency"][2:] == 0)),
        "correct_efficiency_zero_sum": math.isclose(float(advantages["efficiency"].sum()), 0),
        "unclipped_numeric_derivative": math.isclose(derivative, float(advantages["combined"][0]) / 8, rel_tol=1e-8),
        "empty_eligible_set_zero_redundancy": trajectory_cost([], total_calls=2, category="Challenging",
                                                             threshold=threshold, seed=seed)[0] == 0,
        "missing_complete_score_redundant": trajectory_cost([None], total_calls=1, category="Challenging",
                                                             threshold=threshold, seed=seed)[0] == 1,
    }
    return {"seed": seed, "device": "cpu", "evaluation_tier": "l1_mechanism",
            "diagnostic_only": True, "promotion_eligible": False, "evolve_integrated": False,
            "checks": checks, "metrics": {"vfd": score, "threshold": threshold,
                                             "sampled_eligible_index": selected, "trajectory_cost": cost,
                                             "numeric_objective_derivative": derivative},
            "training_executed": False,
            "visual_agent_evaluation_executed": False}
